package xin.v5ai.vault.domain;

import com.baomidou.mybatisplus.annotation.TableId;
import com.baomidou.mybatisplus.annotation.TableName;
import lombok.Data;

import java.io.Serial;
import java.io.Serializable;
import java.util.Date;

/**
 * One bound copy of a cloud vault (design §8.2).
 *
 * A vault directory is bound by its replica id, kept in that directory's
 * `.v5notes/vault.json` and never synced. The device id names the machine the
 * copy runs on, so one machine running several libraries, or re-binding after a
 * reinstall, can be told apart from a second machine. Quota counts replicas.
 */
@Data
@TableName("vault_replica")
public class VaultReplica implements Serializable {

    @Serial
    private static final long serialVersionUID = 1L;

    @TableId(value = "id")
    private Long id;

    private Long vaultId;

    private Long userId;

    /** Copy identity, from vault.json binding.replicaId. */
    private String replicaId;

    /** Machine identity, generated by the client once per install. */
    private String deviceId;

    private String clientInfo;

    private Date lastSeenAt;

    private Date createTime;

    private Date updateTime;
}
